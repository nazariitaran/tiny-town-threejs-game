#!/usr/bin/env node
// Writes public/licenses.txt: every runtime dependency, transitively, with its version, licence, source
// and full licence text, which MIT and the SIL Open Font License require to travel with the copies.
// Run: npm run gen:licenses
//      node scripts/gen-licenses.mjs --check   (fails if the file is stale)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'public/licenses.txt');
const RULE = '-'.repeat(72);

const TITLES = {
  three: 'three.js',
  'lil-gui': 'lil-gui (the ?debug tuning panel)',
  '@fontsource-variable/nunito': 'Nunito variable font (packaged by Fontsource)',
};

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

function packageDir(name) {
  const dir = join(root, 'node_modules', name);
  if (!existsSync(join(dir, 'package.json'))) throw new Error(`${name} is not installed: run npm install`);
  return dir;
}

function sourceUrl(pkg) {
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (!repo) return pkg.homepage ?? '';
  return repo.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '');
}

function licenceText(dir, name) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  if (!file) throw new Error(`${name} ships no LICENSE file: add its licence text by hand`);
  return readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
}

const packages = new Map();
const queue = Object.keys(readJson(join(root, 'package.json')).dependencies ?? {});
while (queue.length) {
  const name = queue.shift();
  if (packages.has(name)) continue;
  const dir = packageDir(name);
  const pkg = readJson(join(dir, 'package.json'));
  packages.set(name, { dir, pkg });
  queue.push(...Object.keys(pkg.dependencies ?? {}));
}

const entries = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = [
  'Tiny Town: open-source licences',
  '===============================',
  '',
  'Tiny Town is built with the open-source software below. Each entry gives the',
  'package, its version, its licence and where it comes from, followed by the full',
  'licence text. Credits for the 3D models, sounds and music are in the game',
  '(Menu > Help > Credits).',
  '',
  'Generated by scripts/gen-licenses.mjs from package.json; do not edit by hand.',
  '',
  ...entries.map(([name, { pkg }], i) => `  ${i + 1}. ${TITLES[name] ?? name} ${pkg.version} (${pkg.license})`),
  '',
];
for (const [name, { dir, pkg }] of entries) {
  lines.push(RULE, `${TITLES[name] ?? name}`, `Package: ${name} ${pkg.version}`, `Licence: ${pkg.license}`);
  const source = sourceUrl(pkg);
  if (source) lines.push(`Source: ${source}`);
  if (pkg.homepage && pkg.homepage !== source) lines.push(`Homepage: ${pkg.homepage}`);
  lines.push(RULE, '', licenceText(dir, name), '');
}
const text = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('public/licenses.txt is out of date with the installed dependencies: run npm run gen:licenses');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`public/licenses.txt: ${entries.length} packages`);
}
