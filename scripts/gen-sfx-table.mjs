#!/usr/bin/env node
// Regenerates src/audio/sfxTable.ts from scripts/data/audio.json.
// Run: npm run gen:sfx
import { readFileSync, writeFileSync } from 'node:fs';

const entries = JSON.parse(readFileSync('scripts/data/audio.json', 'utf8'));
const lines = entries.map((e) => {
  const files = e.files.map((f) => `'${f}'`).join(', ');
  return `  '${e.event}': { files: [${files}], group: '${e.group}', volume: ${e.suggestedVolume}, pitchJitter: ${e.pitchJitter}, cooldownMs: ${e.cooldownMs}${e.playbackRate !== undefined ? `, playbackRate: ${e.playbackRate}` : ''} },`;
});
const out = `// GENERATED by scripts/gen-sfx-table.mjs from scripts/data/audio.json — do not edit by hand.
import type { SfxEvent } from './sfx';

export interface SfxEntry {
  files: readonly string[];
  group: 'ui' | 'sfx';
  volume: number;
  pitchJitter: number;
  cooldownMs: number;
  /** Default 1; undo and redo share one file at different rates. */
  playbackRate?: number;
}

export const SFX_TABLE: Record<SfxEvent, SfxEntry> = {
${lines.join('\n')}
};
`;
writeFileSync('src/audio/sfxTable.ts', out);
console.log(`wrote src/audio/sfxTable.ts (${entries.length} events)`);
